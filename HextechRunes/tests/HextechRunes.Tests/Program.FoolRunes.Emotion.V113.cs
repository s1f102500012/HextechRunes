// 悲喜组（苦中作乐、悲喜交加、破涕为笑）。夹具不开始战斗：原版抽牌/生成/变化命令需要进行中的战斗与界面，
// 测试覆盖触发判定、选牌与各类不触发的路径；"触发后真的抽牌/加入喜悦/变化"要实机确认。
internal static partial class Program
{
	/// <summary>
	/// 苦中作乐与悲喜交加的"生成悲伤"判定同原版万事无忧/肥料：生成者是持有者、牌是悲伤，另要求悲伤归持有者；
	/// 队友生成的、生成给队友的、生成的不是悲伤（含悲喜交加自己加入的喜悦）、持有者不是愚者或已死亡都不触发。
	/// </summary>
	[HextechTest]
	private static void FoolEmotionSadnessGenerationMatchesVanillaCreatorRule()
	{
		List<Player> players = CreateFoolPileTestPlayers(2);
		Player owner = players[0], teammate = players[1];
		BittersweetRune bittersweet = CreateMutableTestModel<BittersweetRune>();
		bittersweet.Owner = owner;
		MixedFeelingsRune mixedFeelings = CreateMutableTestModel<MixedFeelingsRune>();
		mixedFeelings.Owner = owner;

		Sadness ownSadness = AddFoolTestCard<Sadness>(owner, PileType.Hand);
		Sadness teammateSadness = AddFoolTestCard<Sadness>(teammate, PileType.Hand);
		Joy ownJoy = AddFoolTestCard<Joy>(owner, PileType.Draw);

		foreach ((string name, Func<CardModel, Player?, bool> rule) in new (string, Func<CardModel, Player?, bool>)[]
		{
			("Bittersweet", bittersweet.IsOwnSadnessGeneration),
			("Mixed Feelings", mixedFeelings.IsOwnSadnessGeneration)
		})
		{
			Expect(rule(ownSadness, owner), $"{name}: own generated Sadness triggers");
			Expect(!rule(ownSadness, teammate), $"{name}: Sadness generated by a teammate does not trigger");
			Expect(!rule(ownSadness, null), $"{name}: Sadness without a creator does not trigger");
			Expect(!rule(teammateSadness, owner), $"{name}: Sadness generated into a teammate's piles does not trigger");
			Expect(!rule(ownJoy, owner), $"{name}: generating Joy is not generating Sadness");
		}

		List<Player> mixed = CreateFoolPileTestPlayers(1, "FOOL-PILES", typeof(Ironclad));
		BittersweetRune foreign = CreateMutableTestModel<BittersweetRune>();
		foreign.Owner = mixed[0];
		Expect(!foreign.IsOwnSadnessGeneration(AddFoolTestCard<Sadness>(mixed[0], PileType.Hand), mixed[0]), "non-Fool holders do not trigger");

		AccessTools.Field(typeof(MegaCrit.Sts2.Core.Entities.Creatures.Creature), "_currentHp").SetValue(owner.Creature, 0);
		Expect(!bittersweet.IsOwnSadnessGeneration(ownSadness, owner), "dead holders do not trigger");
	}

	/// <summary>不满足判定时两个钩子都不动牌堆：苦中作乐不抽牌，悲喜交加不往抽牌堆加喜悦。</summary>
	[HextechTest]
	private static void FoolEmotionHooksLeavePilesAloneWhenNotTriggered()
	{
		List<Player> players = CreateFoolPileTestPlayers(2);
		Player owner = players[0], teammate = players[1];
		BittersweetRune bittersweet = CreateMutableTestModel<BittersweetRune>();
		bittersweet.Owner = owner;
		MixedFeelingsRune mixedFeelings = CreateMutableTestModel<MixedFeelingsRune>();
		mixedFeelings.Owner = owner;
		CardModel topOfDraw = AddFoolTestCard<StrikeIronclad>(owner, PileType.Draw);
		Sadness teammateSadness = AddFoolTestCard<Sadness>(teammate, PileType.Hand);
		Joy joy = AddFoolTestCard<Joy>(owner, PileType.Draw);

		bittersweet.AfterCardGeneratedForCombat(teammateSadness, teammate).GetAwaiter().GetResult();
		bittersweet.AfterCardGeneratedForCombat(joy, owner).GetAwaiter().GetResult();
		mixedFeelings.AfterCardGeneratedForCombat(teammateSadness, teammate).GetAwaiter().GetResult();
		mixedFeelings.AfterCardGeneratedForCombat(joy, owner).GetAwaiter().GetResult();

		SequenceEqual(new CardModel[] { topOfDraw, joy }, PileType.Draw.GetPile(owner).Cards, "draw pile is untouched");
		Equal(0, PileType.Hand.GetPile(owner).Cards.Count, "nothing was drawn");
		SequenceEqual(new CardModel[] { teammateSadness }, PileType.Hand.GetPile(teammate).Cards, "teammate's hand is untouched");
	}

	/// <summary>
	/// 破涕为笑选牌：手牌里的悲伤全部选中，按手牌顺序；其他牌（含喜悦）不选，别的牌堆里的悲伤不选。
	/// </summary>
	[HextechTest]
	private static void FoolTearsToLaughterSelectsEverySadnessInHand()
	{
		Player owner = CreateFoolPileTestPlayers(1)[0];
		TearsToLaughterRune rune = CreateMutableTestModel<TearsToLaughterRune>();
		rune.Owner = owner;

		Equal(0, rune.GetSadnessInHand().Count, "empty hand selects nothing");
		AddFoolTestCard<StrikeIronclad>(owner, PileType.Hand);
		AddFoolTestCard<Joy>(owner, PileType.Hand);
		Equal(0, rune.GetSadnessInHand().Count, "a hand without Sadness selects nothing");

		Sadness first = AddFoolTestCard<Sadness>(owner, PileType.Hand);
		AddFoolTestCard<StrikeIronclad>(owner, PileType.Hand);
		Sadness second = AddFoolTestCard<Sadness>(owner, PileType.Hand);
		Sadness third = AddFoolTestCard<Sadness>(owner, PileType.Hand);
		AddFoolTestCard<Sadness>(owner, PileType.Draw);
		AddFoolTestCard<Sadness>(owner, PileType.Discard);
		SequenceEqual(new CardModel[] { first, second, third }, rune.GetSadnessInHand(), "every Sadness in hand, in hand order, and nothing from other piles");
	}

	/// <summary>
	/// 破涕为笑只在持有者自己弃牌结算之后（AfterFlush）触发：队友结束回合、手里没有悲伤、持有者不是愚者时都不变化。
	/// </summary>
	[HextechTest]
	private static void FoolTearsToLaughterSkipsTeammatesAndEmptyHands()
	{
		List<Player> players = CreateFoolPileTestPlayers(2);
		Player owner = players[0], teammate = players[1];
		TearsToLaughterRune rune = CreateMutableTestModel<TearsToLaughterRune>();
		rune.Owner = owner;
		Sadness sadness = AddFoolTestCard<Sadness>(owner, PileType.Hand);
		AddFoolTestCard<Sadness>(teammate, PileType.Hand);

		rune.AfterFlush(new BlockingPlayerChoiceContext(), teammate, [], []).GetAwaiter().GetResult();
		SequenceEqual(new CardModel[] { sadness }, PileType.Hand.GetPile(owner).Cards, "a teammate ending the turn transforms nothing");
		Expect(PileType.Hand.GetPile(teammate).Cards.Single() is Sadness, "teammate's Sadness is untouched");

		PileType.Hand.GetPile(owner).RemoveInternal(sadness);
		AddFoolTestCard<Joy>(owner, PileType.Hand);
		rune.AfterFlush(new BlockingPlayerChoiceContext(), owner, [], []).GetAwaiter().GetResult();
		Expect(PileType.Hand.GetPile(owner).Cards.Single() is Joy, "no Sadness in hand: nothing happens");

		Player ironclad = CreateFoolPileTestPlayers(1, "FOOL-PILES", typeof(Ironclad))[0];
		TearsToLaughterRune foreign = CreateMutableTestModel<TearsToLaughterRune>();
		foreign.Owner = ironclad;
		Sadness ironcladSadness = AddFoolTestCard<Sadness>(ironclad, PileType.Hand);
		foreign.AfterFlush(new BlockingPlayerChoiceContext(), ironclad, [], []).GetAwaiter().GetResult();
		SequenceEqual(new CardModel[] { ironcladSadness }, PileType.Hand.GetPile(ironclad).Cards, "non-Fool holders transform nothing");
	}
}
